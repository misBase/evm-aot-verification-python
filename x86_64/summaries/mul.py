"""go-hpc-evm amd64 output summary for compileEVMMul slices."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, Iterable, List, Sequence, Tuple, Union

from z3 import BitVec, BitVecVal

from common.uint256 import Uint256
from state.smt_state import MemoryDomain, SMTState
from x86_64.disassembler import parse_operands
from x86_64.models import Register, X86Block, X86Instruction

from .base import SummaryContinuation, SummaryDiscoveryContext, X86Summary


MUL_SUMMARY_KIND = "mul"
_UINT64_MASK = (1 << 64) - 1
_FLAGS = ("CF", "ZF", "SF", "OF")


@dataclass(frozen=True)
class ConstLimbLocation:
    value: int


@dataclass(frozen=True)
class RegisterLimbLocation:
    reg: Register


@dataclass(frozen=True)
class StackLimbLocation:
    offset: int


LimbLocation = Union[ConstLimbLocation, RegisterLimbLocation, StackLimbLocation]


@dataclass(frozen=True)
class MulSummary:
    entry_addr: int
    start_block_addr: int
    start_instruction_index: int
    continuation_instruction_index: int
    p_limb_locs: Tuple[LimbLocation, LimbLocation, LimbLocation, LimbLocation]
    q_limb_locs: Tuple[LimbLocation, LimbLocation, LimbLocation, LimbLocation]
    result_stack_offsets: Tuple[int, int, int, int]
    clobber_registers: Tuple[Register, ...]


class MulSummaryMatchError(ValueError):
    pass


class MulSummarySpec:
    kind = MUL_SUMMARY_KIND

    def __init__(
        self,
        *,
        prove_hits: bool = True,
        proof_timeout_ms: int = 10_000,
    ):
        self.prove_hits = prove_hits
        self.proof_timeout_ms = proof_timeout_ms
        self.proof_stats = {"proven": 0, "cache_hits": 0, "failed_cache_hits": 0}

    def discover(
        self,
        ctx: SummaryDiscoveryContext,
        *,
        strict: bool = False,
    ) -> Iterable[X86Summary]:
        summaries = discover_mul_summaries(ctx.blocks, strict=strict)
        for summary in summaries.values():
            if self.prove_hits:
                self._prove_hit(ctx, summary)
            yield X86Summary(
                kind=self.kind,
                entry_addr=summary.entry_addr,
                start_block_addr=summary.start_block_addr,
                start_instruction_index=summary.start_instruction_index,
                continuation=SummaryContinuation(
                    summary.start_block_addr,
                    summary.continuation_instruction_index,
                ),
                covered_block_addrs=(summary.start_block_addr,),
                clobber_registers=summary.clobber_registers,
                payload=summary,
            )

    def _prove_hit(
        self,
        ctx: SummaryDiscoveryContext,
        summary: MulSummary,
    ) -> None:
        """fail-closed：对命中的 raw slice 跑 glue 证明，失败则 raise 穿透。

        证明失败说明 matcher 接受了一段语义可疑的 slice，是 soundness bug
        信号，因此 fallback 模式下同样报错，不静默回退。
        """
        # lazy import：mul_proof 顶层 import 本模块的 location 类型。
        from .mul_proof import MulProofError, prove_mul_slice_cached

        block = ctx.blocks_by_addr[summary.start_block_addr]
        slice_insns = block.instructions[
            summary.start_instruction_index:summary.continuation_instruction_index
        ]
        try:
            status = prove_mul_slice_cached(
                summary,
                slice_insns,
                timeout_ms=self.proof_timeout_ms,
            )
        except MulProofError as exc:
            if exc.from_cache:
                self.proof_stats["failed_cache_hits"] += 1
            raise
        self.proof_stats[status] += 1

    def apply(
        self,
        summary: X86Summary,
        state: SMTState,
        *,
        fresh_prefix: str,
    ) -> SMTState:
        if not isinstance(summary.payload, MulSummary):
            raise TypeError(
                "MUL summary payload must be MulSummary, "
                f"got {type(summary.payload)!r}"
            )
        return apply_mul_summary(
            summary.payload,
            state,
            fresh_prefix=fresh_prefix,
        )


def discover_mul_summaries(
    blocks: Sequence[X86Block],
    *,
    strict: bool = False,
) -> Dict[Tuple[int, int], MulSummary]:
    """Discover same-block slices generated by amd64 compileEVMMul."""
    summaries: Dict[Tuple[int, int], MulSummary] = {}
    failures: List[str] = []

    for block in blocks:
        index = 0
        while index < len(block.instructions):
            if not _looks_like_mul_entry(block.instructions, index):
                index += 1
                continue
            try:
                summary = _match_mul_at(block, index)
            except MulSummaryMatchError as exc:
                if strict:
                    failures.append(
                        f"0x{block.start_addr:x}:{index}: {exc}"
                    )
                index += 1
                continue

            summaries[(summary.start_block_addr, summary.start_instruction_index)] = summary
            index = max(summary.continuation_instruction_index, index + 1)

    if strict and failures:
        joined = "; ".join(failures)
        raise MulSummaryMatchError(f"unmatched MUL-like x86 slice(s): {joined}")
    return summaries


def apply_mul_summary(
    summary: MulSummary,
    state: SMTState,
    *,
    fresh_prefix: str = "mul_summary",
) -> SMTState:
    """Apply the trusted MUL summary to the x86 stack state."""
    new_state = state.copy()
    p = Uint256(*[_limb_location_expr(loc, state) for loc in summary.p_limb_locs])
    q = Uint256(*[_limb_location_expr(loc, state) for loc in summary.q_limb_locs])
    result = Uint256.mul_codegen_order(p, q)  # 与 EVM MUL 同形（值 == p.mul_semantics(q)，见 test_uint256）

    r14 = state.x86_registers.get_register(Register.R14)
    for offset, limb in zip(
        summary.result_stack_offsets,
        (result.z0, result.z1, result.z2, result.z3),
        strict=True,
    ):
        new_state.x86_memory = new_state.x86_memory.store_limb(
            r14 + BitVecVal(offset, 64),
            limb,
            domain=MemoryDomain.STACK,
        )

    for reg in summary.clobber_registers:
        new_state.x86_registers.set_register(
            reg,
            BitVec(f"{fresh_prefix}_{summary.entry_addr:x}_{reg.value}", 64),
        )
    for flag in _FLAGS:
        new_state.x86_registers.set_flag(
            flag,
            BitVec(f"{fresh_prefix}_{summary.entry_addr:x}_{flag}", 1),
        )
    return new_state


class _MulParser:
    def __init__(self, block: X86Block, start_index: int):
        self.block = block
        self.insns = block.instructions
        self.index = start_index
        self.written_regs: set[Register] = set()
        self.param_reg: Register | None = None
        self.tmp1_reg: Register | None = None
        self.tmp2_reg: Register | None = None
        self.tmp3_reg: Register | None = None
        self.res1_reg: Register | None = None
        self.res2_reg: Register | None = None
        self.res3_reg: Register | None = None
        self.res4_reg: Register | None = None
        self.p_locs: list[LimbLocation | None] = [None, None, None, None]
        self.q_locs: list[LimbLocation | None] = [None, None, None, None]

    def parse(self) -> MulSummary:
        self._parse_q1_row()
        self._parse_q2_row()
        self._parse_q3_row()
        self._parse_q4_row()
        result_offsets = self._parse_result_stores()

        self._require_complete_locations()
        self._require_distinct_role_registers()
        clobbers = tuple(sorted(self.written_regs, key=lambda reg: reg.value))
        return MulSummary(
            entry_addr=self.insns[self.start_index].addr,
            start_block_addr=self.block.start_addr,
            start_instruction_index=self.start_index,
            continuation_instruction_index=self.index,
            p_limb_locs=tuple(self.p_locs),  # type: ignore[arg-type]
            q_limb_locs=tuple(self.q_locs),  # type: ignore[arg-type]
            result_stack_offsets=result_offsets,
            clobber_registers=clobbers,
        )

    @property
    def start_index(self) -> int:
        return self._start_index

    @start_index.setter
    def start_index(self, value: int) -> None:
        self._start_index = value

    def _parse_q1_row(self) -> None:
        self.start_index = self.index
        q1, p1 = self._parse_mul_pair()
        self.q_locs[0] = q1
        self.p_locs[0] = self._remember_p_loc(0, p1)

        self._expect_mov_reg_from_reg(Register.RAX, dest_role="res1")
        self.res1_reg = self._last_dest_reg
        self._expect_mov_reg_from_reg(Register.RDX, dest_role="tmp1")
        self.tmp1_reg = self._last_dest_reg

        self._parse_q1_hop(1, self.tmp1_reg, "tmp1", "tmp2")
        self._parse_q1_hop(2, self.tmp2_reg, "tmp2", "tmp3")

        q1_again, p4 = self._parse_mul_pair()
        self._expect_same_location(q1_again, self.q_locs[0], "q1")
        self.p_locs[3] = self._remember_p_loc(3, p4)
        self._expect_add_to_rax(self.tmp3_reg, "tmp3")
        self._expect_adc_zero_to_rdx()
        self._expect_mov_from_rax_to(self.tmp3_reg, "tmp3")

    def _parse_q1_hop(
        self,
        p_index: int,
        add_reg: Register | None,
        add_role: str,
        next_tmp_role: str,
    ) -> None:
        q1, p_loc = self._parse_mul_pair()
        self._expect_same_location(q1, self.q_locs[0], "q1")
        self.p_locs[p_index] = self._remember_p_loc(p_index, p_loc)
        self._expect_add_to_rax(add_reg, add_role)
        self._expect_adc_zero_to_rdx()
        self._expect_mov_from_rax_to(add_reg, add_role)
        self._expect_mov_reg_from_reg(Register.RDX, dest_role=next_tmp_role)
        if next_tmp_role == "tmp2":
            self.tmp2_reg = self._last_dest_reg
        elif next_tmp_role == "tmp3":
            self.tmp3_reg = self._last_dest_reg
        else:
            raise MulSummaryMatchError(f"unknown tmp role {next_tmp_role}")

    def _parse_q2_row(self) -> None:
        if self._try_parse_zero_row(self.tmp1_reg, "tmp1", "res2"):
            self.q_locs[1] = ConstLimbLocation(0)
            return

        q2, p1 = self._parse_mul_pair()
        self.q_locs[1] = q2
        self._expect_same_location(p1, self.p_locs[0], "p1")
        self._expect_add_to_rax(self.tmp1_reg, "tmp1")
        self._expect_adc_zero_to_rdx()
        self._expect_mov_reg_from_reg(Register.RAX, dest_role="res2")
        self.res2_reg = self._last_dest_reg
        self._expect_mov_reg_from_reg(Register.RDX, dest_role="tmp1")
        self.tmp1_reg = self._last_dest_reg

        self._parse_q2_hop(1, self.tmp2_reg, "tmp2", self.tmp1_reg, "tmp1", "tmp2", "tmp1")
        self._parse_q2_hop(2, self.tmp3_reg, "tmp3", self.tmp1_reg, "tmp1", "tmp3", None)

    def _parse_q2_hop(
        self,
        p_index: int,
        first_add: Register | None,
        first_role: str,
        second_add: Register | None,
        second_role: str,
        result_tmp_role: str,
        carry_tmp_role: str | None,
    ) -> None:
        q2, p_loc = self._parse_mul_pair()
        self._expect_same_location(q2, self.q_locs[1], "q2")
        self._expect_same_location(p_loc, self.p_locs[p_index], f"p{p_index + 1}")
        self._expect_add_to_rax(first_add, first_role)
        self._expect_adc_zero_to_rdx()
        self._expect_add_to_rax(second_add, second_role)
        self._expect_adc_zero_to_rdx()
        self._expect_mov_reg_from_reg(Register.RAX, dest_role=result_tmp_role)
        result_reg = self._last_dest_reg
        if result_tmp_role == "tmp2":
            self.tmp2_reg = result_reg
        elif result_tmp_role == "tmp3":
            self.tmp3_reg = result_reg
        else:
            raise MulSummaryMatchError(f"unknown result tmp role {result_tmp_role}")
        if carry_tmp_role is not None:
            self._expect_mov_reg_from_reg(Register.RDX, dest_role=carry_tmp_role)
            if carry_tmp_role == "tmp1":
                self.tmp1_reg = self._last_dest_reg
            else:
                raise MulSummaryMatchError(f"unknown carry tmp role {carry_tmp_role}")

    def _parse_q3_row(self) -> None:
        if self._try_parse_zero_row(self.tmp2_reg, "tmp2", "res3"):
            self.q_locs[2] = ConstLimbLocation(0)
            return

        q3, p1 = self._parse_mul_pair()
        self.q_locs[2] = q3
        self._expect_same_location(p1, self.p_locs[0], "p1")
        self._expect_add_to_rax(self.tmp2_reg, "tmp2")
        self._expect_adc_zero_to_rdx()
        self._expect_mov_reg_from_reg(Register.RAX, dest_role="res3")
        self.res3_reg = self._last_dest_reg
        self._expect_mov_reg_from_reg(Register.RDX, dest_role="tmp1")
        self.tmp1_reg = self._last_dest_reg

        q3_again, p2 = self._parse_mul_pair()
        self._expect_same_location(q3_again, self.q_locs[2], "q3")
        self._expect_same_location(p2, self.p_locs[1], "p2")
        self._expect_add_to_rax(self.tmp3_reg, "tmp3")
        self._expect_adc_zero_to_rdx()
        self._expect_add_to_rax(self.tmp1_reg, "tmp1")
        self._expect_adc_zero_to_rdx()
        self._expect_mov_reg_from_reg(Register.RAX, dest_role="tmp3")
        self.tmp3_reg = self._last_dest_reg

    def _parse_q4_row(self) -> None:
        if self._try_parse_zero_row(self.tmp3_reg, "tmp3", "res4"):
            self.q_locs[3] = ConstLimbLocation(0)
            return

        q4, p1 = self._parse_mul_pair()
        self.q_locs[3] = q4
        self._expect_same_location(p1, self.p_locs[0], "p1")
        self._expect_add_to_rax(self.tmp3_reg, "tmp3")
        self._expect_adc_zero_to_rdx()
        self._expect_mov_reg_from_reg(Register.RAX, dest_role="res4")
        self.res4_reg = self._last_dest_reg

    def _parse_result_stores(self) -> Tuple[int, int, int, int]:
        result_regs = (self.res1_reg, self.res2_reg, self.res3_reg, self.res4_reg)
        offsets = []
        for role, reg in zip(("res1", "res2", "res3", "res4"), result_regs, strict=True):
            if reg is None:
                raise MulSummaryMatchError(f"{role} register was not established")
            offsets.append(self._expect_stack_store(reg, role))
        return tuple(offsets)  # type: ignore[return-value]

    def _parse_mul_pair(self) -> tuple[LimbLocation, LimbLocation]:
        q_loc = self._expect_load_to_reg(Register.RAX, "q")
        p_loc = self._expect_load_to_reg(None, "p")
        self._remember_param_reg(self._last_dest_reg)
        self._expect_mul_by_param()
        return q_loc, p_loc

    def _try_parse_zero_row(
        self,
        tmp_reg: Register | None,
        tmp_role: str,
        res_role: str,
    ) -> bool:
        if tmp_reg is None or self.index >= len(self.insns):
            return False
        insn = self.insns[self.index]
        if not _is_mov_mnemonic(insn):
            return False
        ops = parse_operands(insn)
        if (
            ops.get("src_reg") != tmp_reg
            or ops.get("dest_reg") is None
            or ops.get("is_memory")
        ):
            return False
        self.index += 1
        self._consume_write(ops["dest_reg"])
        if res_role == "res2":
            self.res2_reg = ops["dest_reg"]
        elif res_role == "res3":
            self.res3_reg = ops["dest_reg"]
        elif res_role == "res4":
            self.res4_reg = ops["dest_reg"]
        else:
            raise MulSummaryMatchError(f"unknown result role {res_role}")
        _ = tmp_role
        return True

    def _expect_load_to_reg(
        self,
        expected_dest: Register | None,
        role: str,
    ) -> LimbLocation:
        insn = self._next(f"missing {role} load")
        if not _is_mov_mnemonic(insn):
            raise MulSummaryMatchError(
                f"expected {role} load, got {insn.mnemonic} {insn.op_str}"
            )
        ops = parse_operands(insn)
        dest = ops.get("dest_reg")
        if dest is None:
            raise MulSummaryMatchError(f"{role} load does not write a register")
        if expected_dest is not None and dest != expected_dest:
            raise MulSummaryMatchError(
                f"{role} load writes {dest}, expected {expected_dest}"
            )
        loc = _source_limb_location(insn)
        if loc is None:
            raise MulSummaryMatchError(f"unsupported {role} load source: {insn.op_str}")
        self._consume_write(dest)
        self._last_dest_reg = dest
        self._last_param_location = loc
        return loc

    def _expect_mul_by_param(self) -> None:
        insn = self._next("missing mul")
        if insn.mnemonic.lower() != "mul":
            raise MulSummaryMatchError(f"expected mul, got {insn.mnemonic} {insn.op_str}")
        ops = parse_operands(insn)
        if ops.get("dest_reg") != self.param_reg or ops.get("dest_size") != 8:
            raise MulSummaryMatchError("mul does not use the recovered param register")
        self.written_regs.add(Register.RAX)
        self.written_regs.add(Register.RDX)

    def _expect_add_to_rax(self, src_reg: Register | None, role: str) -> None:
        if src_reg is None:
            raise MulSummaryMatchError(f"{role} register was not established")
        insn = self._next(f"missing add {role} to rax")
        ops = parse_operands(insn)
        if (
            insn.mnemonic.lower() != "add"
            or ops.get("dest_reg") != Register.RAX
            or ops.get("src_reg") != src_reg
        ):
            raise MulSummaryMatchError(
                f"expected add rax, {role}, got {insn.mnemonic} {insn.op_str}"
            )
        self._consume_write(Register.RAX)

    def _expect_adc_zero_to_rdx(self) -> None:
        insn = self._next("missing adc rdx, 0")
        ops = parse_operands(insn)
        if (
            insn.mnemonic.lower() != "adc"
            or ops.get("dest_reg") != Register.RDX
            or ops.get("immediate") != 0
        ):
            raise MulSummaryMatchError(
                f"expected adc rdx, 0, got {insn.mnemonic} {insn.op_str}"
            )
        self._consume_write(Register.RDX)

    def _expect_mov_from_rax_to(self, dest_reg: Register | None, role: str) -> None:
        if dest_reg is None:
            raise MulSummaryMatchError(f"{role} register was not established")
        insn = self._next(f"missing mov rax to {role}")
        ops = parse_operands(insn)
        if (
            not _is_mov_mnemonic(insn)
            or ops.get("dest_reg") != dest_reg
            or ops.get("src_reg") != Register.RAX
            or ops.get("is_memory")
        ):
            raise MulSummaryMatchError(
                f"expected mov {role}, rax, got {insn.mnemonic} {insn.op_str}"
            )
        self._consume_write(dest_reg)

    def _expect_mov_reg_from_reg(self, src_reg: Register, *, dest_role: str) -> None:
        insn = self._next(f"missing mov {dest_role}")
        ops = parse_operands(insn)
        if (
            not _is_mov_mnemonic(insn)
            or ops.get("src_reg") != src_reg
            or ops.get("dest_reg") is None
            or ops.get("is_memory")
        ):
            raise MulSummaryMatchError(
                f"expected mov {dest_role}, {src_reg.value}, got "
                f"{insn.mnemonic} {insn.op_str}"
            )
        self._consume_write(ops["dest_reg"])
        self._last_dest_reg = ops["dest_reg"]

    def _expect_stack_store(self, src_reg: Register, role: str) -> int:
        insn = self._next(f"missing {role} store")
        ops = parse_operands(insn)
        if (
            not _is_mov_mnemonic(insn)
            or not ops.get("is_memory")
            or ops.get("base_reg") != Register.R14
            or ops.get("memory_size") != 8
            or ops.get("src_reg") != src_reg
        ):
            raise MulSummaryMatchError(
                f"expected stack store for {role}, got {insn.mnemonic} {insn.op_str}"
            )
        return ops["offset"]

    def _remember_param_reg(self, reg: Register | None) -> None:
        if reg is None:
            raise MulSummaryMatchError("param register was not loaded")
        if reg in {Register.RAX, Register.RDX}:
            raise MulSummaryMatchError("param register overlaps reserved RAX/RDX")
        if self.param_reg is None:
            self.param_reg = reg
        elif self.param_reg != reg:
            raise MulSummaryMatchError(
                f"param register changed from {self.param_reg} to {reg}"
            )

    def _remember_p_loc(self, index: int, loc: LimbLocation) -> LimbLocation:
        prior = self.p_locs[index]
        if prior is not None:
            self._expect_same_location(loc, prior, f"p{index + 1}")
        return loc

    def _expect_same_location(
        self,
        loc: LimbLocation,
        expected: LimbLocation | None,
        label: str,
    ) -> None:
        if expected is None:
            raise MulSummaryMatchError(f"{label} location was not established")
        if loc != expected:
            raise MulSummaryMatchError(
                f"{label} location mismatch: {loc!r} != {expected!r}"
            )

    def _require_complete_locations(self) -> None:
        for label, locs in (("p", self.p_locs), ("q", self.q_locs)):
            for index, loc in enumerate(locs, start=1):
                if loc is None:
                    raise MulSummaryMatchError(f"{label}{index} location missing")
                if (
                    isinstance(loc, RegisterLimbLocation)
                    and loc.reg in self.written_regs
                ):
                    raise MulSummaryMatchError(
                        f"{label}{index} source register is clobbered: {loc.reg}"
                    )

    def _require_distinct_role_registers(self) -> None:
        """纵深防御：param/tmp*/res* 角色寄存器必须互不重叠。

        Go 侧 allocateRegisters(..., 8) 返回 8 个不同寄存器；角色重叠意味着
        结果寄存器可能被后续段当 tmp 覆盖，slice 语义不再可信。
        """
        roles = {
            "param": self.param_reg,
            "tmp1": self.tmp1_reg,
            "tmp2": self.tmp2_reg,
            "tmp3": self.tmp3_reg,
            "res1": self.res1_reg,
            "res2": self.res2_reg,
            "res3": self.res3_reg,
            "res4": self.res4_reg,
        }
        seen: dict[Register, str] = {}
        for role, reg in roles.items():
            if reg is None:
                continue
            prior = seen.get(reg)
            if prior is not None:
                raise MulSummaryMatchError(
                    f"role registers overlap: {prior} and {role} both use {reg}"
                )
            seen[reg] = role

    def _next(self, message: str) -> X86Instruction:
        if self.index >= len(self.insns):
            raise MulSummaryMatchError(message)
        insn = self.insns[self.index]
        self.index += 1
        return insn

    def _consume_write(self, reg: Register) -> None:
        self.written_regs.add(reg)


def _match_mul_at(block: X86Block, start_index: int) -> MulSummary:
    parser = _MulParser(block, start_index)
    return parser.parse()


def _looks_like_mul_entry(insns: Sequence[X86Instruction], index: int) -> bool:
    if index + 4 >= len(insns):
        return False
    first, second, third, fourth, fifth = insns[index:index + 5]
    if not (_is_mov_mnemonic(first) and _is_mov_mnemonic(second)):
        return False
    first_ops = parse_operands(first)
    second_ops = parse_operands(second)
    if first_ops.get("dest_reg") != Register.RAX:
        return False
    param_reg = second_ops.get("dest_reg")
    if param_reg is None or param_reg in {Register.RAX, Register.RDX}:
        return False
    third_ops = parse_operands(third)
    if third.mnemonic.lower() != "mul" or third_ops.get("dest_reg") != param_reg:
        return False
    fourth_ops = parse_operands(fourth)
    fifth_ops = parse_operands(fifth)
    return (
        _is_mov_mnemonic(fourth)
        and fourth_ops.get("src_reg") == Register.RAX
        and fourth_ops.get("dest_reg") is not None
        and _is_mov_mnemonic(fifth)
        and fifth_ops.get("src_reg") == Register.RDX
        and fifth_ops.get("dest_reg") is not None
    )


def _source_limb_location(insn: X86Instruction) -> LimbLocation | None:
    ops = parse_operands(insn)
    if ops.get("src_reg") is not None:
        return RegisterLimbLocation(ops["src_reg"])
    if ops.get("immediate") is not None:
        return ConstLimbLocation(ops["immediate"] & _UINT64_MASK)
    if (
        ops.get("is_memory")
        and ops.get("base_reg") == Register.R14
        and ops.get("memory_size") == 8
        and ops.get("dest_reg") is not None
    ):
        return StackLimbLocation(ops["offset"])
    return None


def _limb_location_expr(loc: LimbLocation, state: SMTState):
    if isinstance(loc, ConstLimbLocation):
        return BitVecVal(loc.value & _UINT64_MASK, 64)
    if isinstance(loc, RegisterLimbLocation):
        return state.x86_registers.get_register(loc.reg)
    if isinstance(loc, StackLimbLocation):
        r14 = state.x86_registers.get_register(Register.R14)
        return state.x86_memory.load_limb(
            r14 + BitVecVal(loc.offset, 64),
            domain=MemoryDomain.STACK,
        )
    raise TypeError(f"unknown limb location: {loc!r}")


def _is_mov_mnemonic(insn: X86Instruction) -> bool:
    return insn.mnemonic.lower() in {"mov", "movabs"}
